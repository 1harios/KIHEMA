/**
 * Всплывающее описание карточки.
 *
 * Одно общее состояние на страницу, а не по панели на карточку. В сетке каталога
 * карточек до сорока, в рядах главной — под двести: сорок отдельных панелей с
 * собственными таймерами и запросами были бы дороже всего остального на странице.
 *
 * Почему панель рисуется отдельным слоем, а не внутри карточки. Ряды
 * прокручиваются горизонтально, а overflow-x: auto обрезает содержимое по ОБЕИМ
 * осям — на этом уже погорела анимация подъёма карточки. Панель, растущая внутри
 * карточки, была бы срезана краем ряда. Поэтому она живёт в фиксированном слое, но
 * встаёт по координатам обложки и растёт из её центра — видно карточку, которая
 * увеличилась, а не отдельную табличку рядом.
 *
 * ТРИ БАГА, которые здесь исправлены, — все из-за работы с таймерами:
 *
 * 1. Панель зависала от прошлой карточки. Уход с карточки ставил закрытие с
 *    отсрочкой (чтобы можно было дотянуться до кнопок внутри панели), а вход на
 *    соседнюю карточку вызывал сброс ВСЕХ таймеров — включая это закрытие. Теперь
 *    вход на другую карточку закрывает открытую панель немедленно.
 *
 * 2. Панель появлялась на странице фильма. Таймер открытия переживал переход:
 *    нажали карточку, ушли на страницу тайтла, а через полторы секунды панель
 *    открывалась там по координатам карточки, которой уже нет. Теперь есть reset,
 *    и его вызывает макет при навигации.
 *
 * 3. Панель дёргалась при появлении. Причина была не в анимации, а в том, что
 *    положение зависело от измеренной высоты. Теперь якорь — обложка, и высота на
 *    него не влияет (см. HoverPreview).
 *
 * Устройство состояния такое же, как в истории поиска и прогрессе просмотра:
 * канонические данные в обычных переменных, реактивное состояние — зеркало.
 * Эффект, который читает и пишет одно реактивное состояние, уходит в бесконечный
 * цикл и молча роняет гидрацию всей страницы.
 */

import { browser } from '$app/environment';
import type { CatalogItem, MediaType } from './types';

/** Подробности, которых нет в списочных данных. */
export interface PreviewDetails {
	genres: string[];
	ageRating?: string;
	runtimeMin?: number;
	rating?: number;
	votes?: number;
	overview?: string;
}

/**
 * Координаты ОБЛОЖКИ, а не всей карточки.
 *
 * Панель разворачивается из обложки, поэтому ей нужен прямоугольник самой
 * картинки: по нему считается и место, и точка, из которой панель растёт. Раньше
 * передавалась карточка целиком, и панель наезжала на подпись под постером.
 */
export interface AnchorRect {
	top: number;
	left: number;
	width: number;
	height: number;
}

/** Сколько курсор должен постоять на карточке, прежде чем панель появится. */
const OPEN_DELAY_MS = 1500;
/** Отсрочка закрытия: за это время можно перевести курсор на саму панель. */
const CLOSE_DELAY_MS = 160;

const cache = new Map<string, PreviewDetails>();
const keyOf = (type: MediaType, id: number) => `${type}:${id}`;

let openTimer: ReturnType<typeof setTimeout> | null = null;
let closeTimer: ReturnType<typeof setTimeout> | null = null;
/**
 * Для какой карточки сейчас заряжен таймер открытия. Нужно, чтобы обработчик
 * движения курсора не перезаряжал таймер на каждом пикселе — иначе панель не
 * откроется никогда: отсчёт будет начинаться заново от каждого движения.
 */
let armed: string | null = null;

const state = $state<{
	item: CatalogItem | null;
	rect: AnchorRect | null;
	details: PreviewDetails | null;
	loading: boolean;
}>({ item: null, rect: null, details: null, loading: false });

/**
 * Сама обложка, из которой выросла панель.
 *
 * Держим элемент, а не только снятые координаты: при прокрутке панель обязана
 * ехать вместе с карточкой. Раньше координаты снимались один раз, а любое
 * событие прокрутки просто закрывало панель — и это оказалось причиной жалобы
 * «иногда не появляется»: браузер восстанавливает позицию прокрутки и досылает
 * события уже ПОСЛЕ загрузки страницы, ленивые картинки сдвигают вёрстку, — и
 * панель закрывалась через миг после открытия. В обычном элементе, а не в
 * реактивном состоянии: он нужен только для расчётов.
 */
let anchorEl: HTMLElement | null = null;

/**
 * Сама панель. Нужна, чтобы перед закрытием спросить: а курсор-то где?
 *
 * Панель появляется ПОД неподвижным курсором и накрывает карточку. Браузер в
 * этот момент присылает карточке «уход» (сверху оказался другой элемент), и
 * панель закрывалась через 160 мс, после чего карточка снова получала наведение,
 * снова заряжался таймер, панель снова появлялась — и так по кругу. Со стороны
 * это выглядело то как «не появляется», то как «мигает и лагает».
 *
 * Лечится не отменой закрытия, а проверкой факта: если курсор физически внутри
 * панели или внутри обложки, закрывать нечего.
 */
let panelEl: HTMLElement | null = null;

/** Последняя известная позиция курсора — для той же проверки. */
let pointer = { x: -1, y: -1 };
let pointerBound = false;

function onPointerMove(e: PointerEvent): void {
	pointer = { x: e.clientX, y: e.clientY };
}

/**
 * Слежение за курсором. Включается один раз при первом наведении и больше не
 * снимается: один пассивный обработчик, который пишет два числа, дешевле любой
 * логики включения-выключения — и, главное, позиция нужна ВСЕГДА, а не только
 * пока панель открыта (по ней проверяется, стоит ли вообще открывать).
 */
function bindPointer(): void {
	if (!browser || pointerBound) return;
	pointerBound = true;
	window.addEventListener('pointermove', onPointerMove, { passive: true });
}

const inside = (el: HTMLElement | null): boolean => {
	if (!el || pointer.x < 0) return false;
	const b = el.getBoundingClientRect();
	return pointer.x >= b.left && pointer.x <= b.right && pointer.y >= b.top && pointer.y <= b.bottom;
};

/**
 * Есть ли наведение курсором.
 *
 * На тач-устройствах панели нет: там hover либо не существует, либо эмулируется
 * первым касанием — и тогда первое касание по карточке показывало бы панель
 * вместо открытия фильма. На телевизоре наведения тоже нет, но там панель
 * открывается по фокусу с пульта — см. enterViaFocus.
 */
export const canHover = (): boolean =>
	browser && window.matchMedia('(hover: hover) and (pointer: fine)').matches;

function clearOpen(): void {
	if (openTimer) clearTimeout(openTimer);
	openTimer = null;
	armed = null;
}

function clearClose(): void {
	if (closeTimer) clearTimeout(closeTimer);
	closeTimer = null;
}

async function loadDetails(item: CatalogItem): Promise<void> {
	const key = keyOf(item.type, item.tmdbId);
	const hit = cache.get(key);
	if (hit) {
		state.details = hit;
		state.loading = false;
		return;
	}

	state.loading = true;
	try {
		const res = await fetch(`/api/preview/${item.type}/${item.tmdbId}`);
		if (!res.ok) throw new Error(String(res.status));
		const data = (await res.json()) as PreviewDetails;
		cache.set(key, data);
		// Пока грузили, курсор мог уйти на другую карточку — тогда ответ уже не наш.
		if (state.item?.tmdbId === item.tmdbId && state.item?.type === item.type) {
			state.details = data;
		}
	} catch {
		// Молча: панель остаётся с тем, что было в списочных данных. Сообщать
		// «не удалось загрузить жанры» в поповере не о чем.
	} finally {
		if (state.item?.tmdbId === item.tmdbId) state.loading = false;
	}
}

/** Открыть панель прямо сейчас, без задержки. */
function open(item: CatalogItem, poster: HTMLElement): void {
	/*
		Таймер сработал — значит ничего больше не «заряжено», и флаг обязан
		сброситься ПЕРВЫМ делом, до любых досрочных выходов ниже.

		Это была настоящая утечка состояния: если открытие отменялось (обложку
		увезли прокруткой), флаг оставался выставленным навсегда. После этого
		обработчик движения курсора считал, что таймер уже заряжен, и выходил на
		первой строке — карточка становилась мёртвой до перезагрузки страницы. Ровно
		так «панель иногда не появляется» и выглядит.
	*/
	armed = null;

	/*
		Проверка по факту, а не по событиям.

		Событиями наведения доверять нельзя: браузер присылает «уход из прежней
		карточки» ПОСЛЕ «входа в новую», досылает пары out/over при любом изменении
		вёрстки под курсором, а появившаяся панель забирает наведение себе. На
		событиях эта механика ломалась двумя разными способами — панель то не
		появлялась, то мигала.

		Здесь единственный критерий: курсор физически внутри обложки. Если нет —
		открывать нечего, и никакие пропущенные или лишние события на это не влияют.
	*/
	// Позиция неизвестна (панель открывали с клавиатуры или пультом) — доверяем
	// событиям. Известна и вне обложки — не открываем.
	if (pointer.x >= 0 && !inside(poster)) return;

	const box = poster.getBoundingClientRect();
	// Обложку могли увести за пределы экрана прокруткой, пока шла задержка.
	if (box.bottom < 0 || box.top > window.innerHeight) return;

	anchorEl = poster;
	state.item = item;
	state.rect = { top: box.top, left: box.left, width: box.width, height: box.height };
	state.details = cache.get(keyOf(item.type, item.tmdbId)) ?? null;
	void loadDetails(item);
}

const sameItem = (item: CatalogItem): boolean =>
	state.item?.tmdbId === item.tmdbId && state.item?.type === item.type;

export const preview = {
	get item() {
		return state.item;
	},
	get rect() {
		return state.rect;
	},
	get details() {
		return state.details;
	},
	get loading() {
		return state.loading;
	},

	/**
	 * Курсор на обложке — заряжаем показ.
	 *
	 * Вход и движение делают одно и то же и специально не различаются: вход может
	 * не прийти (панель прошлой карточки накрыла эту), а движение приходит всегда,
	 * пока курсор внутри. Повторные вызовы безвредны — заряд для этой же карточки
	 * не перезапускается, иначе отсчёт начинался бы заново на каждом пикселе.
	 */
	arm(item: CatalogItem, poster: HTMLElement, e?: MouseEvent): void {
		if (!canHover()) return;
		bindPointer();
		/*
			Позицию берём из самого события, а не только из общего слушателя.

			Это важно для первого наведения после загрузки страницы: общий слушатель
			на тот момент ещё не получал ни одного события, позиция неизвестна, и
			проверка геометрии отказала бы показать панель. Событие же несёт
			координаты с собой — значит первое же наведение работает.
		*/
		if (e) pointer = { x: e.clientX, y: e.clientY };

		const key = keyOf(item.type, item.tmdbId);

		// Панель этой карточки уже открыта — ничего делать не нужно, но отложенное
		// закрытие снимаем: курсор вернулся.
		if (sameItem(item)) {
			clearClose();
			return;
		}
		// Заряд уже идёт для этой карточки.
		if (armed === key) return;

		// Открыта панель другой карточки — закрываем сразу, иначе она зависнет.
		if (state.item) this.close();

		armed = key;
		openTimer = setTimeout(() => open(item, poster), OPEN_DELAY_MS);
	},

	/**
	 * Фокус на карточке — путь для клавиатуры и пульта телевизора.
	 *
	 * Вызывать нужно ТОЛЬКО когда фокус пришёл с клавиатуры (:focus-visible):
	 * щелчок мышью тоже даёт фокус, и раньше из-за этого панель открывалась уже
	 * после перехода на страницу фильма.
	 *
	 * Задержка здесь короче: пультом наводятся осознанно, ждать полторы секунды на
	 * каждом шаге по сетке невозможно.
	 */
	enterViaFocus(item: CatalogItem, poster: HTMLElement): void {
		clearOpen();
		if (state.item && !sameItem(item)) {
			clearClose();
			this.close();
		}
		armed = keyOf(item.type, item.tmdbId);
		openTimer = setTimeout(() => open(item, poster), 500);
	},

	/**
	 * Курсор ушёл с карточки. Закрываем не сразу — иначе до панели не дотянуться.
	 *
	 * ВАЖНО: уход адресный. Раньше здесь безусловно снимался таймер открытия, и
	 * это была та самая причина «панель иногда не появляется»: браузер при
	 * переходе между карточками присылает события в порядке «вход в новую» →
	 * «уход из прежней», и уход из прежней убивал таймер, только что заряженный
	 * для новой. Дальше карточка молчала, потому что вход в неё уже случился и
	 * второй раз не придёт.
	 *
	 * Поэтому таймер снимается только если он заряжен для ТОЙ карточки, с которой
	 * ушли. Закрытие открытой панели ставится всегда — она относится к прошлой
	 * карточке в любом случае.
	 */
	/**
	 * Курсор ушёл с карточки.
	 *
	 * Заряд показа здесь НЕ снимается намеренно: событие ухода приходит и когда
	 * человек никуда не уходил — например, панель появилась под неподвижным
	 * курсором. Вместо отмены полагаемся на проверку геометрии в момент
	 * срабатывания: если курсор действительно вне обложки, показ не состоится сам.
	 */
	leave(): void {
		clearClose();
		closeTimer = setTimeout(() => this.closeIfAway(), CLOSE_DELAY_MS);
	},

	/**
	 * Закрыть, если курсор действительно ушёл.
	 *
	 * Проверка по факту, а не по событиям. События здесь врут: панель, появившись
	 * под неподвижным курсором, забирает наведение себе, и карточка честно
	 * сообщает «ушли» — хотя человек не двинулся. Раньше на этом панель гасла, а
	 * потом открывалась заново, и так по кругу.
	 */
	closeIfAway(): void {
		if (inside(panelEl) || inside(anchorEl)) return;
		this.close();
	},

	/** Курсор перешёл на саму панель — отменяем закрытие. */

	/** Курсор перешёл на саму панель — отменяем закрытие. */
	keep(): void {
		clearClose();
	},

	/**
	 * Пересчитать координаты обложки. Вызывает панель при прокрутке и изменении
	 * размеров окна.
	 *
	 * Возвращает false, если обложка ушла с экрана — тогда панель закрывается: она
	 * привязана к карточке, а карточки на экране больше нет.
	 */
	/** Панель сообщает свой корневой элемент — для проверки положения курсора. */
	bindPanel(el: HTMLElement | null): void {
		panelEl = el;
	},

	track(): boolean {
		if (!anchorEl || !state.item) return false;
		const box = anchorEl.getBoundingClientRect();
		// Полностью ушла из кадра — держать панель незачем.
		if (box.bottom < 8 || box.top > window.innerHeight - 8) {
			this.close();
			return false;
		}
		state.rect = { top: box.top, left: box.left, width: box.width, height: box.height };
		return true;
	},

	/**
	 * Закрыть открытую панель.
	 *
	 * НЕ трогает заряд показа — и это принципиально. Раньше здесь снимались все
	 * таймеры, и получалась последняя, самая коварная версия бага: курсор заходит
	 * на новую карточку, заряд поставлен, а через 160 мс срабатывает отложенное
	 * закрытие от УХОДА С ПРЕЖНЕЙ карточки — и вместе с панелью гасит только что
	 * поставленный заряд. Панель после этого появлялась лишь со второй попытки,
	 * то есть «через раз».
	 *
	 * Закрытие панели и отмена показа — разные события, и смешивать их нельзя.
	 */
	close(): void {
		clearClose();
		anchorEl = null;
		panelEl = null;
		state.item = null;
		state.rect = null;
		state.details = null;
		state.loading = false;
	},

	/**
	 * Полный сброс при уходе со страницы. Отдельно от close по смыслу: close —
	 * это «панель закрылась», reset — «страницы, к которой она относилась, больше
	 * нет». Вызывается макетом на навигации, иначе отложенное открытие срабатывает
	 * уже на новой странице.
	 */
	reset(): void {
		// Здесь наоборот: страницы больше нет, значит и заряд показа не нужен.
		clearOpen();
		this.close();
	}
};
